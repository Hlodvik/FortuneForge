import { readFile, writeFile } from 'node:fs/promises'

const definitions = await readFile(new URL('../../../src/FortuneForge.Games.RobotRevolution/FifthSunTotalityDefinitions.cs', import.meta.url), 'utf8')
const wheel = await readFile(new URL('../../../src/FortuneForge.Games.RobotRevolution/FifthSunTotalityWheel.cs', import.meta.url), 'utf8')
const decimal = name => {
  const match = definitions.match(new RegExp(`public const decimal ${name} = ([0-9]+(?:\\.[0-9]+)?)m;`))
  if (!match) throw new Error(`Missing native Eclipse constant: ${name}`)
  return Number(match[1])
}
const rounds = definitions.match(/public const int EclipseRounds = (\d+);/)
const alignments = definitions.match(/public const int AlignmentsPerRound = (\d+);/)
const version = wheel.match(/public const string MathVersion = "([^"]+)";/)
if (!rounds || !alignments || !version) throw new Error('Missing native Eclipse duration, alignments or math version')
const values = {
  ordinaryPayoutMultiplier: decimal('OrdinaryPayoutMultiplier'),
  eclipsePayoutMultiplier: decimal('EclipsePayoutMultiplier'),
  wheelAwardScale: decimal('EclipseWheelScale'),
  totalityAwardMultiplier: decimal('TotalityAwardMultiplier'),
  eclipseRounds: Number(rounds[1]),
  alignmentsPerRound: Number(alignments[1]),
  mathVersion: version[1],
}
const output = new URL('../src/eclipseMath.generated.ts', import.meta.url)
const content = `// Generated by scripts/export-eclipse-math.mjs from the native game constants.\nexport const FIFTH_SUN_ECLIPSE_MATH = ${JSON.stringify(values, null, 2)} as const\n`
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== content) throw new Error('The Eclipse guide metadata is stale; regenerate it from the native game.')
} else {
  await writeFile(output, content, 'utf8')
}
